    private void btnRegistrarMovimientoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarMovimientoActionPerformed
        // TODO add your handling code here:
        int filaSeleccionada = tblCatalogo.getSelectedRow();
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un producto del catálogo para registrar el movimiento.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int productoId = (int) tblCatalogo.getValueAt(filaSeleccionada, 0);
        String tipoMovimiento = cboTipoMovimiento.getSelectedItem().toString();
        String cantidadTexto = txtCantidad.getText().trim();
        String motivo = txtMotivo.getText().trim();

        // Validaciones básicas
        if (cantidadTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe ingresar una cantidad.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int cantidad;
        try {
            cantidad = Integer.parseInt(cantidadTexto);
            if (cantidad <= 0) {
                 JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a 0.", "Error", JOptionPane.ERROR_MESSAGE);
                 return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La cantidad debe ser un número entero válido.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // REGLA DE NEGOCIO: Exigir motivo para mermas y salidas
        if ((tipoMovimiento.equals("Merma") || tipoMovimiento.equals("Salida")) && motivo.isEmpty()) {
             JOptionPane.showMessageDialog(this, "Debe ingresar un motivo obligatorio para mermas o salidas.", "Regla de Negocio", JOptionPane.WARNING_MESSAGE);
             return;
        }
        
        // Si es entrada y no hay motivo, ponemos uno por defecto
        if (tipoMovimiento.equals("Entrada") && motivo.isEmpty()) {
            motivo = "Ingreso de stock inicial";
        }

        // Creamos el movimiento (recordando usar 1 como usuario temporal)
        Movimiento mov = new Movimiento(productoId, tipoMovimiento, cantidad, motivo, 1);

        if (movimientoDAO.registrarMovimiento(mov)) {
            JOptionPane.showMessageDialog(this, "Movimiento registrado correctamente. El stock se ha actualizado.");
            txtCantidad.setText("");
            txtMotivo.setText("");
            cboTipoMovimiento.setSelectedIndex(0);
            cargarTabla(); // Recargamos la tabla para ver el nuevo stock
        } else {
            JOptionPane.showMessageDialog(this, "Error al registrar el movimiento en la base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnRegistrarMovimientoActionPerformed

