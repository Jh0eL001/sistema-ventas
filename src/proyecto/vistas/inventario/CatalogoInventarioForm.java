    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblCatalogo.getModel();
        modelo.setRowCount(0); // Limpia la tabla antes de cargar

        List<Producto> lista = productoDAO.listarCatalogoConStock();
        for (Producto prod : lista) {
            modelo.addRow(new Object[]{
                prod.getId(),
                prod.getCodigo(),
                prod.getNombre(),
                "General", // Mostrar ID de categoría por ahora
                prod.getCalidad(),
                prod.getPrecio(),
                prod.getStockCalculado() // ¡Aquí se muestra el stock real calculado!
            });
        }
    }
