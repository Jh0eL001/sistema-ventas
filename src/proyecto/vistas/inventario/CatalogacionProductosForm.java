    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
            // TODO add your handling code here:
            if (cboCajaOrigen.getSelectedItem() == null) {
                JOptionPane.showMessageDialog(this, "No hay cajas abiertas seleccionadas.");
                return;
            }

            String seleccion = cboCajaOrigen.getSelectedItem().toString();
            int cajaId = Integer.parseInt(seleccion.split(" - ")[0]);

            String codigo = txtCodigo.getText().trim();
            String nombre = txtNombre.getText().trim();
            String material = txtMaterial.getText().trim();
            String pesoTxt = txtPeso.getText().trim();
            String calidad = txtCalidad.getText().trim();
            String costoTxt = txtCosto.getText().trim();
            String precioTxt = txtPrecio.getText().trim();

            if (codigo.isEmpty() || nombre.isEmpty() || pesoTxt.isEmpty() || costoTxt.isEmpty() || precioTxt.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Complete los datos del producto.");
                return;
            }

            try {
                double peso = Double.parseDouble(pesoTxt);
                double costo = Double.parseDouble(costoTxt);
                double precio = Double.parseDouble(precioTxt);

                Producto producto = new Producto(cajaId, codigo, nombre, material, peso, calidad, costo, precio, "sin_foto", "disponible");

                if (productoDAO.registrarProducto(producto)) {
                    JOptionPane.showMessageDialog(this, "Prenda guardada en MariaDB.");
                    txtCodigo.setText("");
                    txtNombre.setText("");
                    txtMaterial.setText("");
                    txtPeso.setText("");
                    txtCalidad.setText("");
                    txtCosto.setText("");
                    txtPrecio.setText("");
                } else {
                    JOptionPane.showMessageDialog(this, "Error al guardar el producto.");
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Peso, costo y precio deben ser números válidos.");
            }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnTerminarCajaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTerminarCajaActionPerformed
        // TODO add your handling code here:
        if (cboCajaOrigen.getSelectedItem() == null) {
            return;
        }

        String seleccion = cboCajaOrigen.getSelectedItem().toString();
        int cajaId = Integer.parseInt(seleccion.split(" - ")[0]);

        if (cajaDAO.actualizarEstadoClasificada(cajaId)) {
            JOptionPane.showMessageDialog(this, "Caja cerrada y clasificada.");
            cargarCajasAbiertas();
        } else {
            JOptionPane.showMessageDialog(this, "Error al clasificar la caja.");
        }
    }//GEN-LAST:event_btnTerminarCajaActionPerformed

